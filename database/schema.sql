-- ------------------------------------------------------------------------------
-- 1. USERS TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE USERS (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR2(255) NOT NULL,
    email           VARCHAR2(255) NOT NULL,
    password_hash   VARCHAR2(255) NOT NULL,
    role            VARCHAR2(50) DEFAULT 'user' NOT NULL,
    is_active       NUMBER(1) DEFAULT 1 NOT NULL,
    avatar_url      VARCHAR2(500),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    last_login_at   TIMESTAMP,
    CONSTRAINT chk_users_role CHECK (role IN ('user', 'admin')),
    CONSTRAINT chk_users_is_active CHECK (is_active IN (0, 1)),
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE INDEX idx_users_email ON USERS(email);
CREATE INDEX idx_users_role ON USERS(role);
CREATE INDEX idx_users_created_at ON USERS(created_at);

COMMENT ON TABLE USERS IS 'User accounts with credentials, roles, and status';
COMMENT ON COLUMN USERS.password_hash IS 'bcrypt salted and hashed password (never stored plaintext)';
COMMENT ON COLUMN USERS.role IS 'user: normal access; admin: administrative privileges';

-- ------------------------------------------------------------------------------
-- 2. ANALYSES TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE ANALYSES (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             NUMBER NOT NULL,
    analysis_type       VARCHAR2(50) NOT NULL,
    input_text          CLOB,
    input_url           VARCHAR2(2000),
    status              VARCHAR2(50) DEFAULT 'pending' NOT NULL,
    overall_assessment  VARCHAR2(100),
    summary             CLOB,
    credibility_score   NUMBER(3, 0),
    sensitivity_level   VARCHAR2(50),
    ai_model_used       VARCHAR2(200),
    processing_time_ms  NUMBER,
    error_message       VARCHAR2(1000),
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_analyses_user FOREIGN KEY (user_id) REFERENCES USERS(id) ON DELETE CASCADE,
    CONSTRAINT chk_analyses_type CHECK (analysis_type IN ('text', 'url')),
    CONSTRAINT chk_analyses_status CHECK (status IN ('pending', 'processing', 'completed', 'failed')),
    CONSTRAINT chk_analyses_score CHECK (credibility_score IS NULL OR (credibility_score >= 0 AND credibility_score <= 100)),
    CONSTRAINT chk_analyses_sensitivity CHECK (sensitivity_level IS NULL OR sensitivity_level IN ('low', 'medium', 'high', 'critical'))
);

CREATE INDEX idx_analyses_user_id ON ANALYSES(user_id);
CREATE INDEX idx_analyses_type ON ANALYSES(analysis_type);
CREATE INDEX idx_analyses_status ON ANALYSES(status);
CREATE INDEX idx_analyses_created_at ON ANALYSES(created_at);

COMMENT ON TABLE ANALYSES IS 'Core source credibility and sensitivity analysis records';
COMMENT ON COLUMN ANALYSES.credibility_score IS 'Calculated credibility score between 0 (lowest) and 100 (highest)';
COMMENT ON COLUMN ANALYSES.sensitivity_level IS 'Sensitivity classification: low, medium, high, critical';

-- ------------------------------------------------------------------------------
-- 3. ANALYSIS_FINDINGS TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE ANALYSIS_FINDINGS (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id     NUMBER NOT NULL,
    finding_type    VARCHAR2(100) NOT NULL,
    category        VARCHAR2(200),
    title           VARCHAR2(500) NOT NULL,
    description     CLOB NOT NULL,
    severity        VARCHAR2(50),
    confidence      VARCHAR2(50),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_findings_analysis FOREIGN KEY (analysis_id) REFERENCES ANALYSES(id) ON DELETE CASCADE,
    CONSTRAINT chk_findings_type CHECK (finding_type IN ('credibility_concern', 'misleading_indicator', 'sensitive_content', 'recommendation')),
    CONSTRAINT chk_findings_severity CHECK (severity IS NULL OR severity IN ('low', 'medium', 'high')),
    CONSTRAINT chk_findings_confidence CHECK (confidence IS NULL OR confidence IN ('low', 'medium', 'high'))
);

CREATE INDEX idx_findings_analysis_id ON ANALYSIS_FINDINGS(analysis_id);
CREATE INDEX idx_findings_type ON ANALYSIS_FINDINGS(finding_type);

COMMENT ON TABLE ANALYSIS_FINDINGS IS 'Granular findings discovered during content analysis';

-- ------------------------------------------------------------------------------
-- 4. SOURCE_REFERENCES TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE SOURCE_REFERENCES (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id     NUMBER NOT NULL,
    title           VARCHAR2(500),
    url             VARCHAR2(2000),
    description     CLOB,
    relevance       VARCHAR2(500),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_refs_analysis FOREIGN KEY (analysis_id) REFERENCES ANALYSES(id) ON DELETE CASCADE
);

CREATE INDEX idx_refs_analysis_id ON SOURCE_REFERENCES(analysis_id);

COMMENT ON TABLE SOURCE_REFERENCES IS 'Authoritative, non-fabricated references retrieved during analysis';

-- ------------------------------------------------------------------------------
-- 5. CONTACT_MESSAGES TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE CONTACT_MESSAGES (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(255) NOT NULL,
    email           VARCHAR2(255) NOT NULL,
    subject         VARCHAR2(500) NOT NULL,
    message         CLOB NOT NULL,
    status          VARCHAR2(50) DEFAULT 'unread' NOT NULL,
    ip_address      VARCHAR2(45),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_contact_status CHECK (status IN ('unread', 'read', 'replied'))
);

CREATE INDEX idx_contact_status ON CONTACT_MESSAGES(status);
CREATE INDEX idx_contact_created_at ON CONTACT_MESSAGES(created_at);

COMMENT ON TABLE CONTACT_MESSAGES IS 'User contact submissions and inquiries';

-- ------------------------------------------------------------------------------
-- 6. AUDIT_LOGS TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE AUDIT_LOGS (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         NUMBER,
    action          VARCHAR2(200) NOT NULL,
    resource_type   VARCHAR2(100),
    resource_id     VARCHAR2(100),
    details         CLOB,
    ip_address      VARCHAR2(45),
    user_agent      VARCHAR2(500),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES USERS(id) ON DELETE SET NULL
);

CREATE INDEX idx_audit_user_id ON AUDIT_LOGS(user_id);
CREATE INDEX idx_audit_action ON AUDIT_LOGS(action);
CREATE INDEX idx_audit_created_at ON AUDIT_LOGS(created_at);

COMMENT ON TABLE AUDIT_LOGS IS 'Immutable security and administrative audit trail';
